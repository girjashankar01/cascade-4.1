import { Link, useLocation } from 'react-router-dom'
import { useWorkspaces } from '../app/workspace-context'
import { Icon } from '../components/ui/Icon'
import { TechnicalDrawer } from '../features/workbench/TechnicalDrawer'
import '../features/pages/pages.css'

/**
 * ProposalPage — shows sources, claims, conflicts, uncertainty labels.
 * Real data comes from the backend GET /sources and GET /claims/{pid}.
 * Until those are connected, this shows the PROP-001 fixture data.
 * All items marked "Demo data" until backend confirms.
 */

interface ClaimRow {
  field: string
  value: string
  quote: string
  page: string
  status: 'GROUNDED' | 'UNCERTAIN' | 'CONFLICTED'
  source: string
}

interface ConflictEntry {
  field: string
  quoteA: { source: string; quote: string; value: string }
  quoteB: { source: string; quote: string; value: string }
  status: 'UNRESOLVED' | 'RESOLVED'
}

// ─── PROP-001 fixture data (from expected_claims.json and data/) ─────────────
const SOURCES = [
  { filename: 'proposal.pdf', kind: 'PDF', sha256: '5fa4c…(Demo data)', pages: 1 },
  { filename: 'forum_post.txt', kind: 'Text', sha256: '7bc3d…(Demo data)', pages: null },
]

const CLAIMS_PROP001: ClaimRow[] = [
  {
    field: 'amount',
    value: '5,000,000 USDC (raw: 5000000)',
    quote: 'This proposal requests a payout of $5.0M (5,000,000 USDC) to the designated recipient address 0x9965507D1a55BCC6475675304Ca994970De97744.',
    page: '1',
    status: 'GROUNDED',
    source: 'proposal.pdf',
  },
  {
    field: 'recipient',
    value: '0x9965507D1a55BCC6475675304Ca994970De97744 (Honest recipient)',
    quote: 'This proposal requests a payout of $5.0M (5,000,000 USDC) to the designated recipient address 0x9965507D1a55BCC6475675304Ca994970De97744.',
    page: '1',
    status: 'GROUNDED',
    source: 'proposal.pdf',
  },
  {
    field: 'amount (forum)',
    value: '5,800,000 USDC',
    quote: 'The revised allocation discussed in working group sessions is $5.8M (5,800,000 USDC).',
    page: 'N/A',
    status: 'CONFLICTED',
    source: 'forum_post.txt',
  },
]

const CONFLICTS: ConflictEntry[] = [
  {
    field: 'amount',
    quoteA: { source: 'proposal.pdf (p.1)', quote: 'payout of $5.0M (5,000,000 USDC) to the designated recipient', value: '5,000,000 USDC' },
    quoteB: { source: 'forum_post.txt', quote: 'revised allocation discussed in working group sessions is $5.8M (5,800,000 USDC)', value: '5,800,000 USDC' },
    status: 'UNRESOLVED',
  },
]

const STATUS_CLASS: Record<ClaimRow['status'], string> = {
  GROUNDED:  'claim-tag--grounded',
  UNCERTAIN: 'claim-tag--uncertain',
  CONFLICTED: 'claim-tag--conflicted',
}

export function ProposalPage() {
  const { active } = useWorkspaces()
  const location = useLocation()

  return (
    <section className="secondary-page" aria-labelledby="proposal-page-title">
      <header className="secondary-page-header">
        <h1 id="proposal-page-title">Proposal</h1>
        <p>Sources, extracted claims, and evidence conflicts for the active proposal.</p>
        <span className="source-label demo-badge">Demo data · PROP-001</span>
      </header>

      <div className="ai-label-notice">
        <Icon name="details" />
        <span>All claim extractions below are <strong>cached</strong> — generated by the AI pipeline and saved. No new LLM call was made for this view.</span>
      </div>

      {/* Sources */}
      <article className="page-card">
        <h2>Source documents</h2>
        <p className="card-lead">Only document hashes go on-chain. The documents themselves stay off-chain.</p>
        <ul className="sources-list">
          {SOURCES.map(s => (
            <li key={s.filename} className="source-item">
              <span className="source-filename">{s.filename}</span>
              <span className="source-kind">{s.kind}</span>
              {s.pages !== null && <span>{s.pages} page{s.pages !== 1 ? 's' : ''}</span>}
              <code className="source-hash" title={s.sha256}>SHA-256: {s.sha256}</code>
            </li>
          ))}
        </ul>
      </article>

      {/* Conflicts — shown first because an UNRESOLVED conflict blocks manifest confirmation */}
      {CONFLICTS.length > 0 && (
        <article className="page-card page-card--alert">
          <h2>Evidence conflicts</h2>
          <p className="card-lead">An unresolved conflict blocks manifest confirmation. Both quotes are shown below.</p>
          {CONFLICTS.map((c, i) => (
            <div key={i} className="conflict-block">
              <h3>Field: <strong>{c.field}</strong> — <span className={`conflict-status conflict-status--${c.status.toLowerCase()}`}>{c.status}</span></h3>
              <div className="conflict-quotes">
                <div className="conflict-quote">
                  <p className="conflict-source">{c.quoteA.source}</p>
                  <blockquote>"{c.quoteA.quote}"</blockquote>
                  <p className="conflict-value">Claimed value: <strong>{c.quoteA.value}</strong></p>
                </div>
                <div className="conflict-quote conflict-quote--disagreement">
                  <p className="conflict-source">{c.quoteB.source}</p>
                  <blockquote>"{c.quoteB.quote}"</blockquote>
                  <p className="conflict-value">Claimed value: <strong>{c.quoteB.value}</strong></p>
                </div>
              </div>
              {c.status === 'UNRESOLVED' && (
                <p className="conflict-block-notice" role="alert">This conflict is unresolved. The proposer must resolve it before a manifest can be confirmed.</p>
              )}
            </div>
          ))}
        </article>
      )}

      {/* Claims table */}
      <article className="page-card">
        <h2>Extracted claims</h2>
        <p className="card-lead">Every claim must carry a quote found in the source, with page number. A quote not found in the source is dropped.</p>
        <div className="claims-table-wrapper">
          <table className="claims-table" aria-label="Extracted proposal claims">
            <thead>
              <tr>
                <th scope="col">Field</th>
                <th scope="col">Claimed value</th>
                <th scope="col">Source quote</th>
                <th scope="col">Page</th>
                <th scope="col">Status</th>
              </tr>
            </thead>
            <tbody>
              {CLAIMS_PROP001.map((claim, i) => (
                <tr key={i}>
                  <td><strong>{claim.field}</strong><br /><small>{claim.source}</small></td>
                  <td>{claim.value}</td>
                  <td className="claim-quote">"{claim.quote}"</td>
                  <td>{claim.page}</td>
                  <td><span className={`claim-tag ${STATUS_CLASS[claim.status]}`}>{claim.status}</span></td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </article>

      <div className="page-actions">
        <Link className="workspace-text-link" to={{ pathname: '/app/manifest', search: location.search }}>
          View manifest and version chain <Icon name="arrow" />
        </Link>
        <TechnicalDrawer result={active.result} />
      </div>
    </section>
  )
}
